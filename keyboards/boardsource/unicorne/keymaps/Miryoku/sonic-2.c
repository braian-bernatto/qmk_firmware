// ------------------------------------------------------
// animation_phase()
// Called periodically from oled_render_anim() to show the next frame
// of whichever animation is appropriate (idle vs. prep vs. tap).
// ------------------------------------------------------
static void animation_phase(void) {
    uint8_t  wpm = get_current_wpm();

    // --------------------------------------
    // IDLE: WPM <= IDLE_SPEED
    // --------------------------------------
    if (wpm <= IDLE_SPEED) {
        // Only advance frames if enough time has passed
        if (timer_elapsed32(idle_anim_timer) > IDLE_FRAME_DURATION) {
            idle_anim_timer = timer_read32();

            // Advance the idle frame
            current_idle_frame = (current_idle_frame + 1) % IDLE_FRAMES;

            // Example: if you want to flip the sequence in reverse each time,
            // you can do: 
            //   oled_write_raw_P(idle[IDLE_FRAMES - 1 - current_idle_frame], ANIM_SIZE);
            // but if you just want them in forward order:
            oled_write_raw_P(idle[current_idle_frame], ANIM_SIZE);
        }
        return;
    }

    // --------------------------------------
    // PREP: WPM in (IDLE_SPEED, TAP_SPEED)
    // --------------------------------------
    if (wpm < TAP_SPEED) {
        // Just show the “prep” frame(s). If you have multiple, you could animate them,
        // but in your code you only have 1 prep image. So:
        oled_write_raw_P(prep[0], ANIM_SIZE);
        return;
    }

    // --------------------------------------
    // TAP: WPM >= TAP_SPEED
    // --------------------------------------
    if (timer_elapsed32(tap_anim_timer) > TAP_FRAME_DURATION) {
        tap_anim_timer = timer_read32();

        current_tap_frame = (current_tap_frame + 1) % TAP_FRAMES;
        oled_write_raw_P(tap[current_tap_frame], ANIM_SIZE);
    }
}

// ------------------------------------------------------
// oled_render_anim()
// This function is called periodically (e.g. from the QMK hook),
// and handles both the OLED sleep logic and the call to animation_phase().
// ------------------------------------------------------
static void oled_render_anim(void) {
    // If we’re typing above IDLE_SPEED, keep the OLED awake
    // and reset the “anim_sleep” timer.
    if (get_current_wpm() > IDLE_SPEED) {
        oled_on();
        anim_sleep = timer_read32();  // reset inactivity timer
    } else {
        // If we’re *not* typing and the inactivity timer has elapsed, turn off.
        if (timer_elapsed32(anim_sleep) > oled_timeout) {
            oled_off();
            return; // No need to animate anything if the screen is off
        }
    }

    // Now check if it’s time to call animation_phase() again.
    // We do this at some regular “tick” interval (ANIM_CALL_INTERVAL).
    if (timer_elapsed32(anim_timer) > ANIM_CALL_INTERVAL) {
        anim_timer = timer_read32();
        animation_phase();
    }
}